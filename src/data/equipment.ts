export function getEquipment(id: string): Equipment | undefined {
  return EQUIPMENT.find((item) => item.id === id);
}

export function describeTool(id: string): { name: string; external: boolean } {
  const gear = getEquipment(id);
  if (gear) return { name: gear.name, external: false };
  const note = ADVISORIES.find((item) => item.id === id);
  if (note) return { name: note.name, external: true };
  return { name: id, external: true };
}
